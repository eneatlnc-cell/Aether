#!/usr/bin/env node
/**
 * 从 .cache/contract-abis.json 重新生成前端 ABI 文件
 *
 * 输出：
 *   src/lib/contracts/AetherRing.abi.ts
 *   src/lib/contracts/AetherGovernance.abi.ts
 *   src/lib/contracts/AetherElection.abi.ts
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const CACHE_PATH = path.join(ROOT, ".cache", "contract-abis.json");
const OUT_DIR = path.join(ROOT, "src", "lib", "contracts");

const CONTRACTS = [
  { name: "AetherRing", abiKey: "AetherRing" },
  { name: "AetherGovernance", abiKey: "AetherGovernance" },
  { name: "AetherElection", abiKey: "AetherElection" },
];

function main() {
  if (!fs.existsSync(CACHE_PATH)) {
    console.error(`[regen-frontend-abi] 缓存文件不存在: ${CACHE_PATH}`);
    process.exit(1);
  }

  const cache = JSON.parse(fs.readFileSync(CACHE_PATH, "utf8"));
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });

  for (const { name, abiKey } of CONTRACTS) {
    const abi = cache[abiKey];
    if (!abi || !Array.isArray(abi)) {
      console.error(`[regen-frontend-abi] 缓存中缺少 ${abiKey} ABI`);
      process.exit(1);
    }

    const header = [
      "// AUTO-GENERATED from contracts/src/" + name + ".sol — DO NOT EDIT",
      "// Generated by scripts/regen-frontend-abi.js",
      "// Solidity 0.8.26, OpenZeppelin Contracts v5",
      "",
    ].join("\n");

    const body = "export const " + name + "ABI = " + JSON.stringify(abi, null, 2) + " as const;\n";

    const outPath = path.join(OUT_DIR, name + ".abi.ts");
    fs.writeFileSync(outPath, header + body, "utf8");
    console.log("[regen-frontend-abi] wrote " + outPath + " (" + abi.length + " entries)");
  }
}

main();
